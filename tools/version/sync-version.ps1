#!/usr/bin/env pwsh
<#
.SYNOPSIS
    版本号唯一来源是仓库根的 VERSION 文件；本脚本把版本号同步到各派生位置，或用 -Check 校验一致性。

.DESCRIPTION
    版本号只允许在仓库根 VERSION（纯文本，一行 X.Y.Z）里修改。派生位置分两类：

      * 构建期自动读取：Directory.Build.props 让所有 .NET 工程拿到 Version / AssemblyVersion /
        FileVersion / InformationalVersion；SafetyNotice 在运行时从程序集版本读；
        packaging/pack.ps1 与 .github/workflows/build.yml 直接读 VERSION。
      * 静态文件需要生成：app.manifest 的 assemblyIdentity、USER_AGREEMENT.txt 的版本行、
        UI 侧 src/Ui/src/lib/version.generated.ts。这三处由本脚本写入。

    默认执行同步（写入）。带 -Check 时不写文件，只比较；不一致就非零退出并列出差异，
    供 devcheck / CI 用来阻止版本漂移。

.EXAMPLE
    pwsh tools/version/sync-version.ps1           # 按 VERSION 同步派生文件
    pwsh tools/version/sync-version.ps1 -Check    # 只校验，不写
#>
[CmdletBinding()]
param(
    [switch]$Check
)

$ErrorActionPreference = 'Stop'

$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$VersionPath = Join-Path $RepoRoot 'VERSION'
if (-not (Test-Path -LiteralPath $VersionPath)) {
    throw "缺少版本文件：$VersionPath（版本号的唯一来源，内容为一行 X.Y.Z）"
}

$Version = (Get-Content -LiteralPath $VersionPath -Raw).Trim()
if ($Version -notmatch '^\d+\.\d+\.\d+$') {
    throw "VERSION 必须是 X.Y.Z 形式的纯版本号，当前为 '$Version'"
}

$script:Utf8 = [System.Text.UTF8Encoding]::new($false)
$script:Changed = [System.Collections.Generic.List[string]]::new()
$script:Drift = [System.Collections.Generic.List[string]]::new()

# 统一按 LF 比较，避免 Windows checkout 的 CRLF 造成假差异。
function Sync-Text {
    param(
        [Parameter(Mandatory)][string]$RelativePath,
        [Parameter(Mandatory)][string]$Content
    )
    $full = Join-Path $RepoRoot $RelativePath
    $target = $Content.Replace("`r`n", "`n")
    $current = if (Test-Path -LiteralPath $full) {
        ([System.IO.File]::ReadAllText($full)).Replace("`r`n", "`n")
    } else {
        $null
    }
    if ($current -eq $target) { return }

    if ($Check) {
        $script:Drift.Add($RelativePath)
        return
    }
    [System.IO.File]::WriteAllText($full, $target, $script:Utf8)
    $script:Changed.Add($RelativePath)
}

# 在已有文本上做定点替换；匹配不到就直接报错，避免版本行被改没了却静默通过。
function Sync-Replace {
    param(
        [Parameter(Mandatory)][string]$RelativePath,
        [Parameter(Mandatory)][string]$Pattern,
        [Parameter(Mandatory)][string]$Replacement
    )
    $full = Join-Path $RepoRoot $RelativePath
    if (-not (Test-Path -LiteralPath $full)) {
        throw "缺少需要同步版本号的文件：$RelativePath"
    }
    $current = ([System.IO.File]::ReadAllText($full)).Replace("`r`n", "`n")
    $regex = [regex]::new($Pattern)
    if (-not $regex.IsMatch($current)) {
        throw "$RelativePath 里匹配不到版本号（规则：$Pattern），请检查文件是否被改写"
    }
    Sync-Text -RelativePath $RelativePath -Content ($regex.Replace($current, $Replacement))
}

# 1) Windows 清单：assemblyIdentity version="X.Y.Z.0"
Sync-Replace -RelativePath 'src/Host/app.manifest' `
    -Pattern '(<assemblyIdentity\s+version=")[^"]*(")' `
    -Replacement "`${1}$Version.0`${2}"

# 2) 用户协议：版本行
Sync-Replace -RelativePath 'USER_AGREEMENT.txt' `
    -Pattern '(?m)^版本：.*$' `
    -Replacement "版本：$Version"

# 3) Web UI：生成 TS 常量（浅色/网页预览与原生兜底值共用）
$ts = @(
    '// <auto-generated />'
    '// 由 tools/version/sync-version.ps1 从仓库根 VERSION 生成，请勿手改。'
    "export const APP_VERSION = '$Version';"
) -join "`n"
Sync-Text -RelativePath 'src/Ui/src/lib/version.generated.ts' -Content ($ts + "`n")

if ($Check) {
    if ($script:Drift.Count) {
        Write-Error ("版本号与 VERSION（$Version）不一致，运行 pwsh tools/version/sync-version.ps1 修正：`n   - " +
            ($script:Drift -join "`n   - "))
        exit 1
    }
    Write-Host "版本号一致：$Version（VERSION 为唯一来源）"
    exit 0
}

if ($script:Changed.Count) {
    Write-Host "已按 VERSION=$Version 同步：$($script:Changed -join '、')"
} else {
    Write-Host "版本号已是 $Version，无需修改"
}
